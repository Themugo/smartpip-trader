@dataclass
class PerformanceMetrics:
    """Plugin performance tracking"""
    total_trades: int = 0
    winning_trades: int = 0
    losing_trades: int = 0
    total_profit: float = 0.0
    total_loss: float = 0.0
    max_drawdown: float = 0.0
    current_drawdown: float = 0.0
    avg_win: float = 0.0
    avg_loss: float = 0.0
    largest_win: float = 0.0
    largest_loss: float = 0.0
    win_rate: float = 0.0
    profit_factor: float = 0.0
    sharpe_ratio: float = 0.0
    last_updated: datetime = field(default_factory=datetime.utcnow)
    
    @property
    def net_profit(self) -> float:
        return self.total_profit + self.total_loss
    
    @property
    def expectancy(self) -> float:
        if self.total_trades == 0:
            return 0.0
        return self.net_profit / self.total_trades
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            "total_trades": self.total_trades,
            "winning_trades": self.winning_trades,
            "losing_trades": self.losing_trades,
            "total_profit": self.total_profit,
            "total_loss": self.total_loss,
            "net_profit": self.net_profit,
            "max_drawdown": self.max_drawdown,
            "current_drawdown": self.current_drawdown,
            "avg_win": self.avg_win,
            "avg_loss": self.avg_loss,
            "largest_win": self.largest_win,
            "largest_loss": self.largest_loss,
            "win_rate": self.win_rate,
            "profit_factor": self.profit_factor,
            "sharpe_ratio": self.sharpe_ratio,
            "expectancy": self.expectancy,
            "last_updated": self.last_updated.isoformat(),
        }
    
    def record_trade(self, profit: float):
        """Record a completed trade"""
        self.total_trades += 1
        if profit > 0:
            self.winning_trades += 1
            self.total_profit += profit
            if profit > self.largest_win:
                self.largest_win = profit
        else:
            self.losing_trades += 1
            self.total_loss += profit
            if profit < self.largest_loss:
                self.largest_loss = profit
        
        # Update derived metrics
        if self.total_trades > 0:
            self.win_rate = (self.winning_trades / self.total_trades) * 100
        if self.total_profit > 0 and self.total_loss != 0:
            self.profit_factor = abs(self.total_profit / self.total_loss)
        if self.avg_win > 0 and self.avg_loss != 0:
            self.avg_win = self.total_profit / max(self.winning_trades, 1)
            self.avg_loss = abs(self.total_loss) / max(self.losing_trades, 1)
        
        self.last_updated = datetime.utcnow()


class StrategyPlugin(ABC):
    """
    Abstract base class for all trading strategy plugins.
    
    All strategy plugins must implement the standard lifecycle methods:
    - initialize(): Called when the plugin is loaded
    - on_tick(): Called for each market tick
    - generate_signal(): Generate a trading signal
    - validate_risk(): Validate signal against risk rules
    - cleanup(): Called when the plugin is unloaded
    
    The plugin system ensures:
    - Isolated execution environment per plugin
    - Standardized signal and risk validation interfaces
    - Hot-reload capability without system restart
    - Version management and compatibility checks
    """
    
    def __init__(self):
        self._metadata: Optional[PluginMetadata] = None
        self._state: PluginState = PluginState.UNLOADED
        self._metrics = PerformanceMetrics()
        self._config: Dict[str, Any] = {}
        self._initialized = False
        self._error: Optional[str] = None
    
    @property
    @abstractmethod
    def metadata(self) -> PluginMetadata:
        """Return plugin metadata"""
        pass
    
    @property
    def state(self) -> PluginState:
        return self._state
    
    @property
    def metrics(self) -> PerformanceMetrics:
        return self._metrics
    
    @property
    def config(self) -> Dict[str, Any]:
        return self._config
    
    @property
    def is_initialized(self) -> bool:
        return self._initialized
    
    @property
    def error(self) -> Optional[str]:
        return self._error
    
    def configure(self, config: Dict[str, Any]) -> None:
        """Configure the plugin with settings"""
        self._config = config
        self._apply_config()
    
    def _apply_config(self) -> None:
        """Apply configuration - override in subclass if needed"""
        pass
    
    @abstractmethod
    async def initialize(self) -> bool:
        """
        Initialize the plugin.
        
        Called once when the plugin is loaded. Should:
        - Setup any required resources
        - Load saved state if available
        - Connect to external services
        - Return True if initialization successful
        
        Returns:
            bool: True if initialization successful, False otherwise
        """
        pass
    
    @abstractmethod
    async def on_tick(self, tick: TickData) -> None:
        """
        Process incoming market tick data.
        
        Called for each market price update. Plugins should:
        - Update internal price history
        - Run any continuous analysis
        - Update internal state
        
        Args:
            tick: TickData containing current market price
        """
        pass
    
    @abstractmethod
    async def generate_signal(self, tick: TickData) -> Optional[Signal]:
        """
        Generate a trading signal based on current market state.
        
        Called after on_tick when the strategy decides to generate a signal.
        Should return None if no signal is generated.
        
        Args:
            tick: Current tick data
            
        Returns:
            Optional[Signal]: Trading signal or None if no signal
        """
        pass
    
    @abstractmethod
    async def validate_risk(self, signal: Signal, account_balance: float) -> RiskValidation:
        """
        Validate a signal against risk rules.
        
        Called before executing a signal. Should validate:
        - Signal parameters against risk limits
        - Position sizing constraints
        - Account balance adequacy
        
        Args:
            signal: Signal to validate
            account_balance: Current account balance
            
        Returns:
            RiskValidation: Validation result with approved amount
        """
        pass
    
    @abstractmethod
    async def cleanup(self) -> None:
        """
        Cleanup resources when plugin is unloaded.
        
        Should:
        - Close any open connections
        - Save state
        - Release resources
        - Log final metrics
        """
        pass
    
    def on_trade_result(self, signal: Signal, profit: float, is_win: bool) -> None:
        """
        Called with the result of a trade executed from this signal.
        
        Override to update strategy-specific performance tracking.
        
        Args:
            signal: The signal that was traded
            profit: Trade profit/loss amount
            is_win: Whether the trade was a winner
        """
        self._metrics.record_trade(profit)
    
    def get_state(self) -> Dict[str, Any]:
        """Get current plugin state for persistence"""
        return {
            "state": self._state.value,
            "config": self._config,
            "metrics": self._metrics.to_dict(),
            "error": self._error,
        }
    
    def pause(self) -> None:
        """Pause the plugin"""
        if self._state == PluginState.RUNNING:
            self._state = PluginState.PAUSED
    
    def resume(self) -> None:
        """Resume the plugin"""
        if self._state == PluginState.PAUSED:
            self._state = PluginState.RUNNING
    
    def _set_state(self, state: PluginState) -> None:
        """Internal state setter"""
        self._state = state
    
    def _set_error(self, error: Optional[str]) -> None:
        """Internal error setter"""
        self._error = error
    
    def __repr__(self) -> str:
        return f"<{self.__class__.__name__} id={self._metadata.id if self._metadata else 'N/A'} state={self._state.value}>"
