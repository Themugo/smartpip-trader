"""
Strategy Plugin Base Class and Data Models

Defines the standard lifecycle interface and data structures for all trading strategy plugins.
"""

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Any, Dict, List, Optional, Tuple
from uuid import UUID, uuid4


class PluginState(Enum):
    """Plugin lifecycle states"""
    UNLOADED = "unloaded"
    LOADING = "loading"
    INITIALIZED = "initialized"
    RUNNING = "running"
    PAUSED = "paused"
    STOPPED = "stopped"
    ERROR = "error"
    UNLOADING = "unloading"


@dataclass
class PluginMetadata:
    """Plugin metadata and identification"""
    id: str
    name: str
    version: str
    author: str
    description: str
    tags: List[str] = field(default_factory=list)
    supported_markets: List[str] = field(default_factory=list)
    min_confidence: float = 60.0
    max_drawdown_tolerance: float = 20.0
    requires_market_data: bool = True
    requires_ml: bool = False
    home_url: Optional[str] = None
    license: str = "MIT"
    api_version: str = "1.0"
    dependencies: List[str] = field(default_factory=list)
    created_at: datetime = field(default_factory=datetime.utcnow)
    updated_at: datetime = field(default_factory=datetime.utcnow)
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "name": self.name,
            "version": self.version,
            "author": self.author,
            "description": self.description,
            "tags": self.tags,
            "supported_markets": self.supported_markets,
            "min_confidence": self.min_confidence,
            "max_drawdown_tolerance": self.max_drawdown_tolerance,
            "requires_market_data": self.requires_market_data,
            "requires_ml": self.requires_ml,
            "home_url": self.home_url,
            "license": self.license,
            "api_version": self.api_version,
            "dependencies": self.dependencies,
            "created_at": self.created_at.isoformat(),
            "updated_at": self.updated_at.isoformat(),
        }
    
    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "PluginMetadata":
        data = data.copy()
        if "created_at" in data and isinstance(data["created_at"], str):
            data["created_at"] = datetime.fromisoformat(data["created_at"])
        if "updated_at" in data and isinstance(data["updated_at"], str):
            data["updated_at"] = datetime.fromisoformat(data["updated_at"])
        return cls(**data)


@dataclass
class TickData:
    """Standardized tick data for strategy consumption"""
    symbol: str
    price: float
    timestamp: datetime = field(default_factory=datetime.utcnow)
    bid: Optional[float] = None
    ask: Optional[float] = None
    volume: Optional[float] = None
    tick_id: Optional[str] = None
    
    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "TickData":
        timestamp = data.get("timestamp")
        if isinstance(timestamp, str):
            timestamp = datetime.fromisoformat(timestamp)
        elif timestamp is None:
            timestamp = datetime.utcnow()
        return cls(
            symbol=data.get("symbol", ""),
            price=float(data.get("price", data.get("quote", 0))),
            timestamp=timestamp,
            bid=data.get("bid"),
            ask=data.get("ask"),
            volume=data.get("volume"),
            tick_id=data.get("tick_id"),
        )
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            "symbol": self.symbol,
            "price": self.price,
            "timestamp": self.timestamp.isoformat(),
            "bid": self.bid,
            "ask": self.ask,
            "volume": self.volume,
            "tick_id": self.tick_id,
        }


@dataclass 
class Signal:
    """Trading signal generated by a strategy"""
    id: str = field(default_factory=lambda: str(uuid4()))
    plugin_id: str = ""
    plugin_name: str = ""
    direction: str = ""  # "CALL" (RISE) or "PUT" (FALL)
    confidence: float = 0.0
    reason: str = ""
    metadata: Dict[str, Any] = field(default_factory=dict)
    timestamp: datetime = field(default_factory=datetime.utcnow)
    price: float = 0.0
    market: str = ""
    valid_until: Optional[datetime] = None
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "plugin_id": self.plugin_id,
            "plugin_name": self.plugin_name,
            "direction": self.direction,
            "confidence": self.confidence,
            "reason": self.reason,
            "metadata": self.metadata,
            "timestamp": self.timestamp.isoformat(),
            "price": self.price,
            "market": self.market,
            "valid_until": self.valid_until.isoformat() if self.valid_until else None,
        }
    
    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "Signal":
        data = data.copy()
        if "timestamp" in data and isinstance(data["timestamp"], str):
            data["timestamp"] = datetime.fromisoformat(data["timestamp"])
        if "valid_until" in data and data["valid_until"]:
            data["valid_until"] = datetime.fromisoformat(data["valid_until"])
        return cls(**data)


